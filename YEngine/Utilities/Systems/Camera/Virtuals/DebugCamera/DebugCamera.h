#pragma once
#include "../VirtualCamera.h"

// ============================================================
// デバッグカメラクラス（開発中の自由な視点移動用カメラ）
//
// 操作（Unity / Unreal のシーンビューと同じ考え方）:
//   右ボタンを押している間だけ「フライ操作」
//     マウス移動 … 見回す
//     WASD      … 前後左右 / Q・E … 下降・上昇（ワールドの上下）
//     Shift     … 速く移動
//     ホイール  … 移動速度を上げ下げ
//   中ボタンドラッグ … 平行移動（パン）
//   ホイール（右ボタンを押していないとき）… 視線方向へ前後
//
// 操作は「ゲーム画面の上で押し始めたとき」だけ始まる。
// パネルで文字を打つ・ショートカットを押す・他のパネルでドラッグする、で
// カメラが動くことはない（以前は WASD/QE が常時効いていた）。
// ============================================================
class DebugCamera : public VirtualCamera {
public:
  // ============================================================
  // 基本関数
  // ============================================================
  void Initialize() override;
  void Update() override;
  void DrawDebugGui() override;

  // ============================================================
  // セーブ・ロード
  // ============================================================
  void Save(nlohmann::json &j) const override;
  void Load(const nlohmann::json &j) override;

  // ============================================================
  // 有効化制御（演出/編集モードからの切替用）
  // ============================================================
  void SetEnabled(bool v) { isMoving_ = v; }
  bool IsEnabled() const { return isMoving_; }

private:
  // ============================================================
  // 内部処理
  // ============================================================
  void UpdateInput();

  // マウスがゲーム画面の上にあり、カメラ操作を始めてよいか
  // （エディタのパネル上・ギズモ操作中は false）
  static bool CanStartMouseControl();

  // 文字入力中か（入力欄に打っている WASD でカメラを動かさない）
  static bool IsTypingText();

private:
  // ============================================================
  // メンバ変数
  // ============================================================
  Vector2 prevMousePos_ = {0.0f, 0.0f};
  bool isFlying_ = false;  // 右ボタンでのフライ操作中
  bool isPanning_ = false; // 中ボタンでの平行移動中
  bool isMoving_ = false;  // デバッグカメラ自体の有効 / 無効

  float rotateSpeed_ = 0.05f;
  float rotateSpeedController_ = 0.005f;
  float moveSpeed_ = 0.5f;
  float moveSpeedController_ = 0.1f;
};
